#!/usr/bin/env node
/**
 * Turns the markdown files in content/articles/ into src/data/articles.generated.js
 * so the app can import article bodies as plain strings (Create React App has no
 * loader for .md, so the content is inlined at build time instead).
 *
 * Run once:   npm run articles
 * Watch mode: npm run articles -- --watch   (used by `npm start`)
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import matter from "gray-matter";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CONTENT_DIR = path.join(ROOT, "content", "articles");
const OUTPUT_FILE = path.join(ROOT, "src", "data", "articles.generated.js");

const DISPLAY_DATE = new Intl.DateTimeFormat("en-GB", {
	day: "numeric",
	month: "long",
	year: "numeric",
	timeZone: "UTC",
});

const relative = (file) => path.relative(ROOT, file);

// "01-my-article.md" -> "my-article"
const slugFromFilename = (filename) =>
	path.basename(filename, path.extname(filename)).replace(/^\d+[-_]/, "");

const parseDate = (value, file) => {
	if (value instanceof Date) return value;
	if (typeof value === "string") {
		const parsed = new Date(value);
		if (!Number.isNaN(parsed.getTime())) return parsed;
	}
	throw new Error(
		`${relative(file)}: "date" is missing or unreadable (use an ISO date, e.g. date: 2025-03-29)`
	);
};

const readArticle = (file) => {
	const { data, content } = matter(fs.readFileSync(file, "utf8"));

	if (!data.title) throw new Error(`${relative(file)}: "title" is required`);
	if (!data.description)
		throw new Error(
			`${relative(file)}: "description" is required (it is used for the article card and meta tags)`
		);

	const date = parseDate(data.date, file);
	const keywords = Array.isArray(data.keywords)
		? data.keywords.map(String)
		: typeof data.keywords === "string"
		? data.keywords.split(",").map((keyword) => keyword.trim())
		: [];

	return {
		slug: String(data.slug || slugFromFilename(file)),
		title: String(data.title),
		description: String(data.description),
		date: date.toISOString().slice(0, 10),
		displayDate: DISPLAY_DATE.format(date),
		keywords,
		// Optional per-article CSS, injected into the article wrapper.
		style: data.style ? String(data.style) : "",
		body: content.trim(),
	};
};

const collect = () => {
	if (!fs.existsSync(CONTENT_DIR)) {
		throw new Error(`No content directory at ${relative(CONTENT_DIR)}`);
	}

	const files = fs
		.readdirSync(CONTENT_DIR)
		.filter((name) => /\.mdx?$/i.test(name) && !name.startsWith("_"))
		.sort()
		.map((name) => path.join(CONTENT_DIR, name));

	const articles = files.map(readArticle);

	const seen = new Map();
	for (const article of articles) {
		if (seen.has(article.slug)) {
			throw new Error(
				`Duplicate slug "${article.slug}" (${seen.get(article.slug)} and ${article.title})`
			);
		}
		seen.set(article.slug, article.title);
	}

	// Newest first; files that share a date keep their filename order.
	return articles
		.map((article, index) => ({ article, index }))
		.sort(
			(a, b) =>
				b.article.date.localeCompare(a.article.date) || a.index - b.index
		)
		.map(({ article }) => article);
};

const write = () => {
	const articles = collect();
	const banner =
		"// AUTO-GENERATED by scripts/build-articles.mjs — do not edit.\n" +
		"// Edit the markdown in content/articles/ and run `npm run articles`.\n\n";
	const next = `${banner}const articles = ${JSON.stringify(articles, null, "\t")};\n\nexport default articles;\n`;

	const current = fs.existsSync(OUTPUT_FILE)
		? fs.readFileSync(OUTPUT_FILE, "utf8")
		: null;

	if (current !== next) {
		fs.writeFileSync(OUTPUT_FILE, next);
	}

	return articles.length;
};

const run = () => {
	try {
		const count = write();
		console.log(
			`[articles] ${count} article${count === 1 ? "" : "s"} → ${relative(OUTPUT_FILE)}`
		);
		return true;
	} catch (error) {
		console.error(`[articles] ${error.message}`);
		return false;
	}
};

const ok = run();

if (process.argv.includes("--watch")) {
	let queued = null;
	fs.watch(CONTENT_DIR, () => {
		clearTimeout(queued);
		queued = setTimeout(run, 50); // editors fire several events per save
	});
	console.log(`[articles] watching ${relative(CONTENT_DIR)}`);
} else if (!ok) {
	process.exit(1);
}
